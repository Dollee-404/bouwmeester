function applyFilters(list: Project[], options: ListOptions): Project[] {
  return list.filter((p) => {
    if (!options.includeArchived && p.isArchived) return false;
    if (options.status && p.status !== options.status) return false;
    if (options.werksoort && p.werksoort !== options.werksoort) return false;
    if (options.search) {
      const q = options.search.toLowerCase();
      if (
        !p.projectName.toLowerCase().includes(q) &&
        !p.customerName.toLowerCase().includes(q)
      ) return false;
    }
    return true;
  });
}

export const mockService: ProjectsService = {
  async list(options = {}) {
    return applyFilters(projects, options);
  },

  async getOne(id) {
    const p = projects.find((p) => p.id === id);
    if (!p) throw new Error(`Project niet gevonden: ${id}`);
    return p;
  },

  async updateStatus(id, newStatus: BouwmeesterStatus) {
    await new Promise((r) => setTimeout(r, 200));
    const p = projects.find((p) => p.id === id);
    if (p) p.status = newStatus;
  },
};
